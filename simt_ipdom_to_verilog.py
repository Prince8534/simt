#!/usr/bin/env python3
"""Convert simt-ipdom-v1 JSON metadata into a synthesizable lookup module."""
import argparse
import json
import re
import sys
from pathlib import Path

HEX_PC = re.compile(r"^0x[0-9a-fA-F]{1,8}$")


def parse_pc(value, where):
    if not isinstance(value, str) or not HEX_PC.fullmatch(value):
        raise ValueError(f"invalid PC for {where}: {value!r}")
    return int(value, 16)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("metadata", type=Path, help="input .ipdom JSON file")
    ap.add_argument("-o", "--output", type=Path, default=Path("simt_ipdom_lookup.v"), help="output Verilog file")
    ap.add_argument("--module", default="simt_ipdom_lookup", help="Verilog module name")
    args = ap.parse_args()
    try:
        data = json.loads(args.metadata.read_text())
        if data.get("format") != "simt-ipdom-v1":
            raise ValueError("unsupported metadata format; expected simt-ipdom-v1")
        if data.get("hardware_metadata_safe") is not True:
            raise ValueError("metadata is not marked hardware_metadata_safe")
        if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_$]*", args.module):
            raise ValueError("invalid Verilog module name")
        mapping = data.get("branch_to_reconvergence")
        if not isinstance(mapping, dict) or not mapping:
            raise ValueError("metadata contains no branch_to_reconvergence entries")
        entries = []
        for branch, reconv in mapping.items():
            entries.append((parse_pc(branch, "branch_to_reconvergence key"),
                            parse_pc(reconv, f"reconvergence for {branch}")))
        entries.sort()
        if len({x[0] for x in entries}) != len(entries):
            raise ValueError("duplicate branch PC")

        lines = [
            "// Generated by simt_ipdom_to_verilog.py; do not edit manually.",
            f"// Source metadata: {args.metadata.name}",
            f"module {args.module} (",
            "    input  wire [31:0] branch_pc,",
            "    output reg  [31:0] reconvergence_pc,",
            "    output reg         metadata_found",
            ");",
            "    always @(*) begin",
            "        reconvergence_pc = 32'h00000000;",
            "        metadata_found = 1'b0;",
            "        case (branch_pc)",
        ]
        for branch, reconv in entries:
            lines.append(f"            32'h{branch:08x}: begin reconvergence_pc = 32'h{reconv:08x}; metadata_found = 1'b1; end")
        lines += [
            "            default: begin reconvergence_pc = 32'h00000000; metadata_found = 1'b0; end",
            "        endcase",
            "    end",
            "endmodule",
            "",
        ]
        args.output.write_text("\n".join(lines))
        print(f"Generated {len(entries)} branch mapping(s) -> {args.output}")
        for branch, reconv in entries:
            print(f"  0x{branch:08x} -> 0x{reconv:08x}")
    except (OSError, json.JSONDecodeError, ValueError) as exc:
        print(f"ipdom converter error: {exc}", file=sys.stderr)
        return 1
    return 0

if __name__ == "__main__":
    raise SystemExit(main())
