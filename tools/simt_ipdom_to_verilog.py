
#!/usr/bin/env python3
"""Convert SIMT IPDOM JSON metadata into a synthesizable Verilog lookup."""

import argparse
import json
import re
import sys
from pathlib import Path

HEX_PC = re.compile(r"^0x[0-9a-fA-F]{1,8}$")
IDENTIFIER = re.compile(r"^[A-Za-z_][A-Za-z0-9_$]*$")


def parse_pc(value, where):
    if not isinstance(value, str) or not HEX_PC.fullmatch(value):
        raise ValueError(f"invalid PC for {where}: {value!r}")
    return int(value, 16)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("metadata", type=Path,
                        help="input .ipdom JSON file")
    parser.add_argument(
        "-o", "--output",
        type=Path,
        default=Path("simt_ipdom_lookup.v"),
        help="output Verilog file"
    )
    parser.add_argument(
        "--module",
        default="simt_ipdom_lookup",
        help="Verilog module name"
    )

    args = parser.parse_args()

    try:
        data = json.loads(args.metadata.read_text())

        if data.get("format") != "simt-ipdom-v1":
            raise ValueError(
                "unsupported metadata format; expected simt-ipdom-v1"
            )

        if data.get("hardware_metadata_safe") is not True:
            raise ValueError(
                "metadata is not marked hardware_metadata_safe"
            )

        if not IDENTIFIER.fullmatch(args.module):
            raise ValueError("invalid Verilog module name")

        regions = data.get("regions")

        if not isinstance(regions, list) or not regions:
            raise ValueError("metadata contains no branch regions")

        branch_entries = []
        join_entries = []

        seen_branches = set()
        seen_joins = set()

        for index, region in enumerate(regions):
            if not isinstance(region, dict):
                raise ValueError(f"region {index} is not an object")

            branch_pc = parse_pc(
                region.get("branch_pc"),
                f"region {index} branch_pc"
            )

            reconvergence_pc = parse_pc(
                region.get("reconvergence_pc"),
                f"region {index} reconvergence_pc"
            )

            fall_join_pc = parse_pc(
                region.get("fallthrough_join_pc"),
                f"region {index} fallthrough_join_pc"
            )

            taken_join_pc = parse_pc(
                region.get("taken_join_pc"),
                f"region {index} taken_join_pc"
            )

            if branch_pc in seen_branches:
                raise ValueError(
                    f"duplicate branch PC 0x{branch_pc:08x}"
                )

            seen_branches.add(branch_pc)

            branch_entries.append(
                (branch_pc, reconvergence_pc)
            )

            for join_pc in (fall_join_pc, taken_join_pc):
                if join_pc in seen_joins:
                    raise ValueError(
                        f"JOIN PC 0x{join_pc:08x} belongs to "
                        "more than one branch"
                    )

                seen_joins.add(join_pc)

                join_entries.append(
                    (join_pc, branch_pc, reconvergence_pc)
                )

        branch_entries.sort()
        join_entries.sort()

        lines = [
            "// Generated by simt_ipdom_to_verilog.py.",
            f"// Source metadata: {args.metadata.name}",
            f"module {args.module} (",
            "    input  wire [31:0] branch_pc,",
            "    output reg  [31:0] reconvergence_pc,",
            "    output reg         metadata_found,",
            "",
            "    input  wire [31:0] join_pc,",
            "    output reg  [31:0] join_owner_branch_pc,",
            "    output reg  [31:0] join_reconvergence_pc,",
            "    output reg         join_metadata_found",
            ");",
            "",
            "    // Branch PC -> reconvergence PC",
            "    always @(*) begin",
            "        reconvergence_pc = 32'h00000000;",
            "        metadata_found = 1'b0;",
            "",
            "        case (branch_pc)"
        ]

        for branch, reconv in branch_entries:
            lines.append(
                f"            32'h{branch:08x}: begin "
                f"reconvergence_pc = 32'h{reconv:08x}; "
                "metadata_found = 1'b1; end"
            )

        lines += [
            "            default: begin",
            "                reconvergence_pc = 32'h00000000;",
            "                metadata_found = 1'b0;",
            "            end",
            "        endcase",
            "    end",
            "",
            "    // JOIN PC -> owning branch and reconvergence PC",
            "    always @(*) begin",
            "        join_owner_branch_pc = 32'h00000000;",
            "        join_reconvergence_pc = 32'h00000000;",
            "        join_metadata_found = 1'b0;",
            "",
            "        case (join_pc)"
        ]

        for join_pc, owner, reconv in join_entries:
            lines.append(
                f"            32'h{join_pc:08x}: begin "
                f"join_owner_branch_pc = 32'h{owner:08x}; "
                f"join_reconvergence_pc = 32'h{reconv:08x}; "
                "join_metadata_found = 1'b1; end"
            )

        lines += [
            "            default: begin",
            "                join_owner_branch_pc = 32'h00000000;",
            "                join_reconvergence_pc = 32'h00000000;",
            "                join_metadata_found = 1'b0;",
            "            end",
            "        endcase",
            "    end",
            "",
            "endmodule",
            ""
        ]

        args.output.write_text("\n".join(lines))

        print(
            f"Generated {len(branch_entries)} branch mapping(s) "
            f"and {len(join_entries)} JOIN mapping(s) -> {args.output}"
        )

        for branch, reconv in branch_entries:
            print(
                f"  branch 0x{branch:08x} -> "
                f"reconvergence 0x{reconv:08x}"
            )

        for join_pc, owner, reconv in join_entries:
            print(
                f"  JOIN 0x{join_pc:08x} -> "
                f"owner 0x{owner:08x}, "
                f"reconvergence 0x{reconv:08x}"
            )

    except (OSError, json.JSONDecodeError, ValueError) as exc:
        print(f"IPDOM converter error: {exc}", file=sys.stderr)
        return 1

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
